"""The robot the demo simulates: a Stretch 4.

Model generated by mujoco-sim's scripts/generate_stretch4_model.py and vendored
in ./stretch4. What the rest of the demo relies on (measured from the model):

- The arm reaches along the base's +x; the omni base strafes along +y, which is
  how the controllers move the gripper sideways along a task.
- Both fingers move together on the one `gripper` actuator (0 = closed, 0.5 =
  open). There are no head actuators.
- grasp_center_link is aligned with the base at a neutral wrist: x = where the
  gripper points, z = up. A held tool (the feeding spoon) is mounted there as is.
- + wrist pitch tips the gripper DOWN (the reverse of the Stretch 3 that
  mujoco-sim's hand mappings were tuned on), so those controllers flip it.
- The wheel actuators are position servos with an unlimited ctrlrange that
  MuJoCo reports as [0, 0]: see sim/base_drive.py.
"""
from pathlib import Path

MODEL_DIR = Path(__file__).parent / "stretch4"
ACTUATORS = (
    "left_wheel_vel", "back_wheel_vel", "right_wheel_vel", "lift", "arm",
    "wrist_yaw", "wrist_pitch", "wrist_roll", "gripper",
)
GRASP_BODY = "grasp_center_link"
